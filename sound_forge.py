def ff():
    import imageio_ffmpeg
    return imageio_ffmpeg.get_ffmpeg_exe()


def _noise(kind="white"):
    if kind == "white":
        return random.uniform(-1, 1)
    if kind == "pink":
        return random.uniform(-1, 1) * .55 + random.uniform(-1, 1) * .3
    return random.uniform(-1, 1) * .3  # brown-ish after integration


def synth(name, seconds=4.0):
    n = int(seconds * SR)
    out = [0.0]*n
    low = 0.0
    env_state = {"last": 0.0}
    def env(x, atk=.01, dec=1.0):
        return min(1.0, x/atk) * math.exp(-x/dec)
    for i in range(n):
        x = i/SR
        v = 0.0
        nm = name.lower()
        if any(k in nm for k in ("ฝน", "rain")):
            v = _noise("white")*.32 + .08*math.sin(2*math.pi*1800*x)
        elif any(k in nm for k in ("ลม", "wind")):
            low = low*.985 + _noise("pink")*.04
            v = low*.9 + _noise("pink")*.06
        elif any(k in nm for k in ("คลื่น", "ทะเล", "ocean")):
            swell = .5+.5*math.sin(2*math.pi*.22*x)
            low = low*.97 + _noise("pink")*.06
            v = low*swell*2.2
        elif any(k in nm for k in ("ฟ้าผ่า", "thunder")):
            v = (_noise("brown")*1.2 if x < 1.2 else 0)*env(x, .02, 2.0)
        elif any(k in nm for k in ("ลำธาร", "stream")):
            v = _noise("pink")*.25 + .12*math.sin(2*math.pi*(900+300*math.sin(x*7))*x)
        elif any(k in nm for k in ("ฝีเท้า", "footstep")):
            ph = x % .55
            v = _noise("white")*env(ph,.005,.06)*.7
        elif any(k in nm for k in ("ปรบมือ", "clap")):
            ph = x % 1.1
            v = _noise("white")*env(ph,.002,.05)*.8
        elif any(k in nm for k in ("หายใจ", "breath")):
            ph = x % 3.2
            v = _noise("pink")*(.5+.5*math.sin(math.pi*ph/1.6))*.4
        elif any(k in nm for k in ("ไอ", "cough")):
            ph = x % 2.0
            v = (_noise("white")*.5+math.sin(2*math.pi*160*x)*.4)*env(ph,.01,.12)
        elif any(k in nm for k in ("หัวเราะ", "laugh")):
            ph = x % 1.0
            v = math.sin(2*math.pi*(280+40*math.sin(x*18))*x)*env(ph,.01,.14)*.5
        elif any(k in nm for k in ("สุนัข", "หมา", "dog")):
            ph = x % 1.4
            v = (_noise("white")*.45+math.sin(2*math.pi*(190-60*ph)*x)*.5)*env(ph,.005,.09)
        elif any(k in nm for k in ("แมว", "cat")):
            ph = x % 2.0
            v = math.sin(2*math.pi*(620-180*ph)*x + .4*math.sin(2*math.pi*9*x))*env(ph,.02,.6)*.5
        elif any(k in nm for k in ("วัว", "cow")):
            ph = x % 3.0
            v = (math.sin(2*math.pi*120*x)+.3*math.sin(2*math.pi*240*x))*env(ph,.05,1.2)*.5
        elif any(k in nm for k in ("กบ", "frog")):
            ph = x % 1.2
            v = math.sin(2*math.pi*(140+40*math.sin(x*25))*x)*env(ph,.01,.16)*.6
        elif any(k in nm for k in ("แมลง", "จิ้งจก", "cicada", "nก")):
            v = (math.sin(2*math.pi*4200*x)*.15+math.sin(2*math.pi*6300*x)*.1)*(.5+.5*math.sin(2*math.pi*11*x))
        elif any(k in nm for k in ("รถไฟ", "train")):
            v = (_noise("brown")*.5+math.sin(2*math.pi*90*x)*.3)*(.7+.3*math.sin(2*math.pi*3*x))
        elif any(k in nm for k in ("รถ", "car", "engine", "พัดลม", "fan")):
            v = math.sin(2*math.pi*(70+12*math.sin(x*2))*x)*.5 + _noise("pink")*.12
        elif any(k in nm for k in ("คีย์บอร์ด", "keyboard", "เครื่องพิมพ์", "printer")):
            ph = x % .28
            v = _noise("white")*env(ph,.001,.022)*.55
        elif any(k in nm for k in ("นาฬิกา", "clock")):
            ph = x % 1.0
            v = math.sin(2*math.pi*2100*x)*env(ph,.001,.02)*.5
        elif any(k in nm for k in ("ไซเรน", "siren")):
            v = math.sin(2*math.pi*(600+300*math.sin(2*math.pi*.5*x))*x)*.4
        elif any(k in nm for k in ("กล้อง", "camera")):
            ph = x % 1.5
            v = _noise("white")*env(ph,.001,.025)*.7
        elif any(k in nm for k in ("whoosh", "วูบ", "เสียว")):
            ph = x % 2.0
            f = 300 + 2600*ph
            v = _noise("pink")*env(ph,.05,.7)*(f/2600)*.6
        elif any(k in nm for k in ("กระดิ่ง", "bell")):
            ph = x % 2.5
            v = (math.sin(2*math.pi*880*x)+.4*math.sin(2*math.pi*1760*x))*env(ph,.005,1.6)*.4
        elif any(k in nm for k in ("ระเบิด", "impact", "boom", "สะท้าน")):
            ph = x % 4.0
            v = (_noise("brown")*1.4)*env(ph,.002,1.2)
        elif any(k in nm for k in ("บี๊บ", "beep")):
            v = math.sin(2*math.pi*1000*x)*(.5+.5*math.sin(2*math.pi*2*x))*.35
        else:
            v = _noise("pink")*.25 + math.sin(2*math.pi*220*x)*.1
        out[i] = max(-1, min(1, v))
    return out, n


def forge(name, seconds=4.0, apply=True):
    buf, n = synth(name, seconds)
    peak = max(1e-6, max(abs(v) for v in buf))
    pcm = b"".join(struct.pack("<h", int(max(-1,min(1,v/peak*.85))*32767)) for v in buf)
    result = {"ok": False, "name": name, "category": next(
        (c for c, names in CATALOG.items() if any(k in name.lower() for k in names)), "sfx")}
    if apply:
        os.makedirs(MEDIA, exist_ok=True)
        wav = os.path.join(MEDIA, "sfx_%d.wav" % int(time.time()*1000))
        with wave.open(wav, "wb") as w:
            w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR)
            w.writeframes(pcm)
        mp3 = MS.to_mp3(wav)
        result.update({"ok": True, "wav": wav, "mp3": mp3,
                       "seconds": seconds, "note": "synthetic sound design (not a field recording)"})
        json.dump(result, open(wav+".json","w",encoding="utf-8"),
                  ensure_ascii=False, indent=2, default=str)
    return result


